const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
    const browser=await chromium.launch({headless:true,channel:'msedge'});
    try {
        const page=await browser.newPage({viewport:{width:2100,height:1000}}),errors=[];
        page.on('pageerror',e=>errors.push(e.message));
        await page.setContent('<div class="rank-chart-row"><section id="concentrationChartPanel" style="width:570px;height:450px"></section><section id="rankAdrChartPanel" style="width:570px;--rank-adr-base-height:450px"></section></div>');
        await page.addStyleTag({content:fs.readFileSync('public/style.css','utf8')});
        await page.evaluate(()=>{
            window.calls=[];window.labels=[];
            Date.now=()=>Date.UTC(2026,8,30);
            window.markers=[];
            const originalArc=CanvasRenderingContext2D.prototype.arc, originalFill=CanvasRenderingContext2D.prototype.fill;
            CanvasRenderingContext2D.prototype.arc=function(x,y,r,...args){this.marker={x,y,r};return originalArc.call(this,x,y,r,...args);};
            CanvasRenderingContext2D.prototype.fill=function(...args){if(this.marker)window.markers.push({...this.marker,color:this.fillStyle});this.marker=null;return originalFill.apply(this,args);};
            const original=CanvasRenderingContext2D.prototype.fillText;
            window.axisLabels=[];
            window.badges=[];window.hoverStrokes=[];
            const originalStroke=CanvasRenderingContext2D.prototype.stroke;
            CanvasRenderingContext2D.prototype.stroke=function(...args){window.hoverStrokes.push({color:this.strokeStyle,dash:this.getLineDash()});return originalStroke.apply(this,args);};
            CanvasRenderingContext2D.prototype.fillText=function(text,...args){window.labels.push(text);if(this.fillStyle==='#ffffff')window.badges.push({text,x:args[0],width:this.canvas.clientWidth});if(text.endsWith('조'))window.axisLabels.push({x:args[0],width:this.canvas.clientWidth});return original.call(this,text,...args);};
            window.fetch=async url=>{window.calls.push(url);const kosdaq=url.includes('kosdaq');return new Response(JSON.stringify({points:Array.from({length:30},(_,i)=>({t:Date.UTC(2026,8,i+1),market_turnover:(kosdaq?5:15)*1e12+i*1e11,open:3000,high:3100,low:2900,close:3050}))}));};
        });
        await page.addScriptTag({content:fs.readFileSync('public/rank-turnover-chart.js','utf8')});
        await page.waitForFunction(()=>document.querySelector('#rankTurnoverChartPanel [role="status"]').textContent.includes('누적값'));
        const panel=page.locator('#rankTurnoverChartPanel');
        assert.equal(await page.evaluate(()=>document.getElementById('rankAdrChartPanel').nextElementSibling.id),'rankTurnoverChartPanel');
        assert.ok(await page.evaluate(()=>window.calls.length===2&&window.calls.every(url=>url.includes('mode=day'))));
        assert.ok(await page.evaluate(()=>['0조','10조','20조'].every(label=>window.labels.includes(label))));
        assert.ok(await page.evaluate(()=>window.axisLabels.every(p=>p.x>p.width/2)),'Turnover Y labels appear on the right');
        assert.ok(await page.evaluate(()=>window.markers.some(p=>p.color==='#f97316'&&p.r===4)),'Today turnover has an orange marker');
        assert.equal(await panel.locator('.turnover-legend').evaluate(el=>el.parentElement.className),'rank-adr-controls');
        assert.equal(await panel.locator('[data-latest="kospi"]').textContent(),'17.90조원');
        assert.equal(await panel.locator('[data-latest="kosdaq"]').textContent(),'7.90조원');
        assert.ok(await panel.locator('[data-latest="kospi"]').evaluate(el=>{
            const s=getComputedStyle(el);return s.fontSize==='16px'&&s.fontWeight==='700'&&s.color==='rgb(51, 154, 240)';
        }),'Turnover latest values use ADR typography');
        assert.ok(await panel.locator('.turnover-legend').evaluate(el=>{
            const legend=el.getBoundingClientRect(),panel=el.closest('.panel').getBoundingClientRect();
            const rows=el.querySelectorAll('[data-market]');
            return getComputedStyle(el).flexDirection==='column'&&legend.right<=panel.right-60&&rows[1].getBoundingClientRect().top>rows[0].getBoundingClientRect().top;
        }),'Today values use two lines aligned with the candle controls and inset from the right edge');
        const chart=panel.locator('.rank-adr-area canvas'), box=await chart.boundingBox();
        await page.mouse.move(box.x+40,box.y+90);
        await page.mouse.down();
        await page.mouse.move(box.x+box.width*.5,box.y+90,{steps:8});
        await page.mouse.up();
        assert.equal(await panel.locator('input').isDisabled(),false,'Left to right drag zooms in');
        await page.mouse.move(box.x+box.width*.6,box.y+90);
        await page.mouse.down();
        await page.mouse.move(box.x+40,box.y+90,{steps:8});
        await page.mouse.up();
        assert.equal(await panel.locator('input').isDisabled(),true,'Right to left drag restores full range');
        await page.mouse.move(box.x+box.width*.4,box.y+100);
        assert.ok(await page.evaluate(()=>window.markers.some(p=>p.color==='#339af0'&&p.r===4)),'Hover draws a market marker');
        const firstX=await page.evaluate(()=>window.markers.filter(p=>p.color==='#339af0'&&p.r===4).at(-1).x);
        await page.mouse.move(box.x+box.width*.6,box.y+100);
        assert.notEqual(await page.evaluate(()=>window.markers.filter(p=>p.color==='#339af0'&&p.r===4).at(-1).x),firstX,'Hover marker follows mouse movement');
        assert.ok(await page.evaluate(()=>window.badges.filter(p=>p.text.endsWith('조')&&p.x>p.width/2).length>=2),'Both markets show right axis value badges');
        assert.ok(await page.evaluate(()=>['#339af0','#e11d48'].every(color=>window.hoverStrokes.some(p=>p.color===color&&p.dash.join(',')==='3,3'))),'Both markets have dotted hover guides');
        assert.ok((await panel.locator('.turnover-hover-info').textContent()).includes('조원'));
        assert.equal(await panel.locator('.turnover-hover-info').evaluate(el=>el.nextElementSibling.className),'rank-adr-area');
        await panel.locator('select').selectOption('kosdaq');
        assert.equal(await panel.locator('[data-market="kosdaq"] > span').evaluate(el=>el.style.opacity),'1');
        assert.equal(await panel.locator('[data-market="kospi"] > span').evaluate(el=>el.style.opacity),'0.3');
        await panel.locator('.concentration-candle-toggle').click();
        assert.equal(await panel.locator('.concentration-candle-toggle').getAttribute('aria-expanded'),'true');
        assert.ok(await panel.locator('.rank-adr-candle-area').isVisible());
        const candleBox=await panel.locator('.rank-adr-candle-area canvas').boundingBox();
        await page.mouse.move(candleBox.x+40,candleBox.y+90);await page.mouse.down();
        await page.mouse.move(candleBox.x+candleBox.width*.5,candleBox.y+90,{steps:8});await page.mouse.up();
        assert.equal(await panel.locator('input').isDisabled(),false,'Candle drag zooms the shared date range');
        await panel.getByRole('button',{name:'거래대금 차트 축소',exact:true}).click();
        await panel.getByRole('button',{name:'거래대금 차트 확대',exact:true}).click();
        assert.equal(await panel.locator('input').isDisabled(),false);
        await panel.locator('[data-range="6m"]').click();
        await page.waitForFunction(()=>window.calls.length===4);
        await panel.locator('.concentration-candle-toggle').click();
        assert.equal(await panel.locator('.rank-adr-candle-area').isVisible(),false);
        assert.deepEqual(errors,[]);
        console.log('PASS turnover daily dual market, 10 trillion ticks, selection, candles, zoom and range');
    } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
