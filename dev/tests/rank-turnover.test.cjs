const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
    const browser=await chromium.launch({headless:true,channel:'msedge'});
    try {
        const page=await browser.newPage({viewport:{width:2100,height:1000}}),errors=[];
        page.on('pageerror',e=>errors.push(e.message));
        await page.setContent('<div class="rank-chart-row"><section id="concentrationChartPanel" style="width:570px;height:450px"></section><section id="rankAdrChartPanel" style="width:570px;--rank-adr-base-height:450px"></section></div>');
        await page.addStyleTag({content:fs.readFileSync('public/style.css','utf8')});
        await page.evaluate(()=>{
            window.calls=[];window.labels=[];
            Date.now=()=>Date.UTC(2026,8,30);
            window.markers=[];
            const originalArc=CanvasRenderingContext2D.prototype.arc, originalFill=CanvasRenderingContext2D.prototype.fill;
            CanvasRenderingContext2D.prototype.arc=function(x,y,r,...args){this.marker={x,y,r};return originalArc.call(this,x,y,r,...args);};
            CanvasRenderingContext2D.prototype.fill=function(...args){if(this.marker)window.markers.push({...this.marker,color:this.fillStyle});this.marker=null;return originalFill.apply(this,args);};
            const original=CanvasRenderingContext2D.prototype.fillText;
            window.axisLabels=[];
            window.candleBodies=[];window.candleAxisLabels=[];
            const originalRect=CanvasRenderingContext2D.prototype.fillRect;
            CanvasRenderingContext2D.prototype.fillRect=function(x,y,w,h){if(this.canvas.closest('#rankTurnoverChartPanel .rank-adr-candle-area')&&['#e11d48','#2563eb'].includes(this.fillStyle))window.candleBodies.push({right:x+w});return originalRect.call(this,x,y,w,h);};
            window.badges=[];window.hoverStrokes=[];
            const originalStroke=CanvasRenderingContext2D.prototype.stroke;
            CanvasRenderingContext2D.prototype.stroke=function(...args){window.hoverStrokes.push({color:this.strokeStyle,dash:this.getLineDash()});return originalStroke.apply(this,args);};
            CanvasRenderingContext2D.prototype.fillText=function(text,...args){window.labels.push(text);if(this.fillStyle==='#ffffff')window.badges.push({text,x:args[0],width:this.canvas.clientWidth});if(text.endsWith('조'))window.axisLabels.push({x:args[0],width:this.canvas.clientWidth,align:this.textAlign});if(this.canvas.closest('#rankTurnoverChartPanel .rank-adr-candle-area')&&/^-?[\d,]+(?:\.\d+)?$/.test(String(text)))window.candleAxisLabels.push({left:args[0]-this.measureText(text).width,value:Number(String(text).replaceAll(',',''))});return original.call(this,text,...args);};
            window.inFlight=0;window.maxInFlight=0;window.refreshPhase=null;
            window.fetch=async url=>{
                window.calls.push(url);window.inFlight++;window.maxInFlight=Math.max(window.maxInFlight,window.inFlight);
                await new Promise(resolve=>setTimeout(resolve,5));window.inFlight--;
                if(window.refreshPhase==='failed')return new Response('{}',{status:502});
                const points = kosdaq => days.map(day=>({t:Date.UTC(2026,8,day),market_turnover:window.refreshPhase==='recent'&&!kosdaq?20e12:(kosdaq?5:15)*1e12+(day-1)*1e11,open:160000,high:3200000,low:150000,close:170000}));
                const days=url.includes('cursor=20260831')?Array.from({length:20},(_,i)=>i-19):window.refreshPhase==='recent'?[30]:Array.from({length:30},(_,i)=>i+1);
                return new Response(JSON.stringify({markets:{kospi:points(false),kosdaq:points(true)},cursor:url.includes('cursor=20260831')?null:'20260831'}));
            };
        });
        await page.addScriptTag({path:'public/rank-chart-axis.js'});
        await page.addScriptTag({content:fs.readFileSync('public/rank-turnover-chart.js','utf8')});
        await page.waitForFunction(()=>document.querySelector('#rankTurnoverChartPanel [role="status"]').textContent.includes('누적값'));
        const panel=page.locator('#rankTurnoverChartPanel');
        assert.equal(await panel.locator('.rank-adr-area canvas').evaluate(node => node.getBoundingClientRect().height), 286, 'Turnover retains the existing plot height');
        assert.equal(await page.evaluate(() => getRankTurnoverCandleOpen()), false);
        await panel.locator('.concentration-candle-toggle').click();
        assert.equal(await page.evaluate(() => getRankTurnoverCandleOpen()), true);
        assert.ok(await page.evaluate(() => window.candleBodies.length && window.candleAxisLabels.length
            && Math.max(...window.candleBodies.map(p=>p.right))+8<=Math.min(...window.candleAxisLabels.map(p=>p.left))),
        'Turnover candles stay clear of the right price-axis labels: ' + JSON.stringify(await page.evaluate(() => ({bodies: window.candleBodies, axes: window.candleAxisLabels}))));
        assert.ok(await page.evaluate(() => window.candleAxisLabels.length>=5&&window.candleAxisLabels.every(p=>p.value>=0)),
        'Turnover index candle axis does not display negative prices');
        await page.evaluate(() => applyRankTurnoverCandleOpen(false));
        assert.equal(await panel.locator('.concentration-candle-toggle').getAttribute('aria-expanded'), 'false');
        await page.evaluate(() => applyRankTurnoverCandleOpen(true));
        assert.equal(await panel.locator('.concentration-candle-toggle').getAttribute('aria-expanded'), 'true');
        await page.evaluate(() => applyRankTurnoverCandleOpen(false));
        assert.equal(await page.evaluate(()=>document.getElementById('rankAdrChartPanel').nextElementSibling.id),'rankTurnoverChartPanel');
        assert.ok(await page.evaluate(()=>window.calls.filter(url=>url.startsWith('/api/turnover/')).length===1&&window.calls.every(url=>url.includes('mode=day'))));
        assert.equal(await page.evaluate(()=>window.maxInFlight),3,'Broker cards fetch independently without duplicating their own request');
        assert.ok(await page.evaluate(()=>['0조','10조','20조'].every(label=>window.labels.includes(label))));
        assert.ok(await page.evaluate(()=>window.axisLabels.every(p=>p.x>p.width/2)),'Turnover Y labels appear on the right');
        assert.ok(await panel.locator('[data-latest="kospi"]').evaluate(output=>{
            const label=window.axisLabels.at(-1),canvas=document.querySelector('#rankTurnoverChartPanel .rank-adr-area canvas');
            return label.align==='right'&&Math.abs(label.x-(label.width-4))<1&&Math.abs(canvas.getBoundingClientRect().left+label.x-output.getBoundingClientRect().right)<1;
        }),'Turnover latest values end at the right edge of the Y-axis labels');
        assert.ok(await page.evaluate(()=>window.markers.some(p=>p.color==='#f97316'&&p.r===4)),'Today turnover has an orange marker');
        assert.equal(await panel.locator('.turnover-legend').evaluate(el=>el.parentElement.className),'rank-adr-controls');
        assert.equal(await panel.locator('[data-latest="kospi"]').textContent(),'17.9조원');
        assert.equal(await panel.locator('[data-latest="kosdaq"]').textContent(),'7.9조원');
        assert.ok(await panel.locator('[data-latest="kospi"]').evaluate(el=>{
            const s=getComputedStyle(el);return s.fontSize==='16px'&&s.fontWeight==='700'&&s.color==='rgb(51, 154, 240)';
        }),'Turnover latest values use ADR typography');
        assert.ok(await panel.locator('.turnover-legend').evaluate(el=>{
            const legend=el.getBoundingClientRect(),panel=el.closest('.panel').getBoundingClientRect();
            const rows=el.querySelectorAll('[data-market]');
            return getComputedStyle(el).flexDirection==='column'&&legend.right<=panel.right&&rows[1].getBoundingClientRect().top>rows[0].getBoundingClientRect().top;
        }),'Today values use two lines aligned with the candle controls and inset from the right edge');
        await page.evaluate(()=>{window.refreshPhase='recent';return window.refreshRankTurnoverChart();});
        assert.equal(await panel.locator('[data-latest="kospi"]').textContent(),'20.0조원');
        assert.ok(await page.evaluate(()=>window.calls.at(-1).includes('/api/turnover/chart?mode=day&cursor=')),'Refresh reuses the loaded page contract');
        await page.evaluate(()=>{window.refreshPhase='failed';return window.refreshRankTurnoverChart();});
        assert.equal(await panel.locator('[data-latest="kospi"]').textContent(),'20.0조원','Failed refresh retains prior data');
        assert.ok((await panel.locator('[role="status"]').textContent()).includes('이전 데이터 표시'));
        await page.evaluate(()=>{window.refreshPhase=null;});
        const chart=panel.locator('.rank-adr-area canvas'), box=await chart.boundingBox();
        await page.mouse.move(box.x+40,box.y+90);
        await page.mouse.down();
        await page.mouse.move(box.x+box.width*.5,box.y+90,{steps:8});
        await page.mouse.up();
        assert.equal(await panel.locator('input[type=range]').isDisabled(),false,'Left to right drag zooms in');
        await page.mouse.move(box.x+box.width*.6,box.y+90);
        await page.mouse.down();
        await page.mouse.move(box.x+40,box.y+90,{steps:8});
        await page.mouse.up();
        assert.equal(await panel.locator('input[type=range]').isDisabled(),true,'Right to left drag restores full range');
        await page.mouse.move(box.x+box.width*.4,box.y+100);
        assert.ok(await page.evaluate(()=>window.markers.some(p=>p.color==='#339af0'&&p.r===4)),'Hover draws a market marker');
        const firstX=await page.evaluate(()=>window.markers.filter(p=>p.color==='#339af0'&&p.r===4).at(-1).x);
        await page.mouse.move(box.x+box.width*.6,box.y+100);
        assert.notEqual(await page.evaluate(()=>window.markers.filter(p=>p.color==='#339af0'&&p.r===4).at(-1).x),firstX,'Hover marker follows mouse movement');
        assert.ok(await page.evaluate(()=>window.badges.filter(p=>p.text.endsWith('조')&&p.x>p.width/2).length>=2),'Both markets show right axis value badges');
        assert.ok(await page.evaluate(()=>['#339af0','#e11d48'].every(color=>window.hoverStrokes.some(p=>p.color===color&&p.dash.join(',')==='3,3'))),'Both markets have dotted hover guides');
        assert.ok((await panel.locator('.turnover-hover-info').textContent()).includes('조원'));
        assert.equal(await panel.locator('.turnover-hover-info').evaluate(el=>el.nextElementSibling.className),'rank-adr-area');
        await panel.locator('input[type=radio][value=kosdaq]').check();
        assert.equal(await panel.locator('[data-market="kosdaq"] > span').evaluate(el=>el.style.opacity),'1');
        assert.equal(await panel.locator('[data-market="kospi"] > span').evaluate(el=>el.style.opacity),'1');
        assert.equal(await panel.locator('[data-latest="kosdaq"]').evaluate(el=>getComputedStyle(el).color),'rgb(225, 29, 72)');
        await panel.locator('.concentration-candle-toggle').click();
        assert.equal(await panel.locator('.concentration-candle-toggle').getAttribute('aria-expanded'),'true');
        assert.ok(await panel.locator('.rank-adr-candle-area').isVisible());
        await panel.locator('.rank-adr-candle-area canvas').scrollIntoViewIfNeeded();
        const candleBox=await panel.locator('.rank-adr-candle-area canvas').boundingBox();
        await page.mouse.move(candleBox.x+40,candleBox.y+90);await page.mouse.down();
        await page.mouse.move(candleBox.x+candleBox.width*.5,candleBox.y+90,{steps:8});await page.mouse.up();
        assert.equal(await panel.locator('input[type=range]').isDisabled(),false,'Candle drag zooms the shared date range');
        await panel.getByRole('button',{name:'거래대금 차트 축소',exact:true}).click();
        await panel.getByRole('button',{name:'거래대금 차트 확대',exact:true}).click();
        assert.equal(await panel.locator('input[type=range]').isDisabled(),false);
        await panel.locator('[data-more]').click();
        await page.waitForFunction(()=>document.querySelector('#rankTurnoverChartPanel [data-more]').disabled);
        assert.equal(await panel.locator('[data-range]').count(),0);
        assert.ok(await page.evaluate(()=>window.calls.some(url=>url.includes('cursor=20260831'))));
        await page.evaluate(()=>window.refreshRankTurnoverChart());
        assert.ok(await page.evaluate(()=>window.calls.slice(-2).some(url=>url.includes('cursor=20260831'))),'Refresh reloads previously appended history');
        await panel.locator('[data-mode="minute"]').click();
        await page.waitForFunction(()=>window.calls.at(-1).includes('mode=minute'));
        assert.equal(await panel.locator('.concentration-candle-toggle').getAttribute('aria-expanded'),'true');
        await panel.locator('.concentration-candle-toggle').click();
        assert.equal(await panel.locator('.rank-adr-candle-area').isVisible(),false);
        assert.deepEqual(errors,[]);
        console.log('PASS turnover daily dual market, 10 trillion ticks, selection, candles, zoom and range');
    } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
