const fs = require('node:fs'), assert = require('node:assert/strict'), { chromium } = require('playwright');
(async () => {
    const browser = await chromium.launch({ headless: true, channel: 'msedge' });
    try {
        const page = await browser.newPage({ viewport: { width: 1800, height: 1100 } }), errors = [], calls = [];
        page.on('pageerror', e => errors.push(e.message));
        const rows = ['2026-10-30T23:58:00+09:00','2026-10-30T23:59:00+09:00','2026-10-31T00:00:00+09:00','2026-10-31T06:00:00+09:00'].map((d,i) => ({t:Date.parse(d),individual:i*100,foreign:-i*100,institution:0}));
        const candles = rows.map(p=>({t:p.t,open:900,high:902,low:898,close:901}));
        let latestOnly=false;
        await page.route('http://futures.test/**', route => {
            const url = new URL(route.request().url()); calls.push(url.pathname+url.search);
            if(url.pathname.endsWith('/candles'))return route.fulfill({json:{success:true,points:latestOnly?candles.slice(-1):candles}});
            if(url.pathname.startsWith('/api/'))return route.fulfill({json:{success:true,points:latestOnly?rows.slice(-1):rows,candles:latestOnly?candles.slice(-1):candles,warnings:[],has_more:false,date:'2026-10-31'}});
            return route.fulfill({contentType:'text/html',body:'<div id="tab_rank"><div class="rank-chart-row"><section class="panel" id="concentrationChartPanel" style="height:450px"></section><section class="panel" id="rankBreadthChartPanel" style="height:450px"></section></div></div>'});
        });
        await page.goto('http://futures.test/');
        await page.addStyleTag({content:fs.readFileSync('public/style.css','utf8')});
        for(const f of ['rank-chart-axis.js','rank-market-supply-chart.js','rank-connection-status.js'])await page.addScriptTag({path:'public/'+f});
        const card=page.locator('#rankTestMarketSupplyChartPanel');
        await page.waitForFunction(()=>window.getTestMarketSupplyCandleDiagnostics?.().flowPoints===4);
        assert.equal(await card.locator('h2').textContent(),'시장수급(테스트)');
        assert.equal(await card.evaluate(el=>el===el.parentElement.lastElementChild),true);
        assert.equal(await card.evaluate(el=>getComputedStyle(el).gridRowStart),'3');
        await card.locator('[data-mode="minute"]').click();
        assert.equal(await card.locator('.market-test-session').count(),0);
        await page.waitForFunction(()=>window.getTestMarketSupplyCandleDiagnostics().flowPoints===4);
        await card.locator('.concentration-candle-toggle').click();
        await page.waitForFunction(()=>window.getTestMarketSupplyCandleDiagnostics().visibleCandles===4);
        const diagnostics=await page.evaluate(()=>window.getTestMarketSupplyCandleDiagnostics());
        assert.equal(diagnostics.visibleFlowPoints,4); assert.equal(diagnostics.visibleCandles,4);
        latestOnly=true;
        await page.evaluate(()=>window.refreshRankTestMarketSupplyChart());
        assert.equal(await page.evaluate(()=>getTestMarketSupplyCandleDiagnostics().flowPoints),4,'Completed refresh retains previously loaded flow');
        assert.equal(await page.evaluate(()=>getTestMarketSupplyCandleDiagnostics().validCandles),4,'Completed refresh retains previously loaded candles');
        latestOnly=false;
        assert.match(await card.locator('.rank-candle-label').textContent(),/KOSPI200.*야간/);
        assert.ok(calls.some(c=>c.startsWith('/api/ls-futures-test/chart?') && c.includes('mode=minute')));
        assert.ok(!calls.some(c=>c.startsWith('/api/adr/candles')),'Test futures must not request spot candles');
        assert.equal(await page.evaluate(()=>getRankCombinedMarketSupplyDisplaySettings().mode),'minute');
        await card.locator('input[value="futuresKosdaq"]').check();
        await page.waitForFunction(()=>window.getTestMarketSupplyCandleDiagnostics().market==='futuresKosdaq' && window.getTestMarketSupplyCandleDiagnostics().visibleCandles===4);
        assert.match(await card.locator('.rank-candle-label').textContent(),/KOSDAQ150/);
        assert.deepEqual(await page.evaluate(()=>({market:getRankCombinedMarketSupplyDisplaySettings().selected,mode:getRankCombinedMarketSupplyDisplaySettings().mode})),{market:'futuresKosdaq',mode:'minute'});
        const target=card.locator('.rank-adr-area canvas');await target.scrollIntoViewIfNeeded();
        const box=await target.boundingBox();
        await page.mouse.move(box.x+12+(box.width-94)*0.2,box.y+80);await page.mouse.down();
        await page.mouse.move(box.x+12+(box.width-94)*0.8,box.y+80,{steps:8});await page.mouse.up();
        await page.waitForFunction(()=>getTestMarketSupplyCandleDiagnostics().visiblePoints===0 && getCombinedMarketSupplyCandleDiagnostics().visiblePoints===0);
        const emptyRange=await page.evaluate(()=>RankChartAxis.minuteDomain());
        assert.ok(emptyRange.first.includes('10-31'),'Zoom into the empty overnight clock interval');
        assert.ok(emptyRange.span>200 && emptyRange.span<230);
        await page.evaluate(()=>RankChartAxis.selectViewport('testMarketSupply',0.8,0.2));
        await page.waitForFunction(()=>getTestMarketSupplyCandleDiagnostics().visibleCandles===4 && getCombinedMarketSupplyCandleDiagnostics().visiblePoints===4);
        await page.setViewportSize({width:600,height:800});
        assert.equal(await card.evaluate(el=>getComputedStyle(el).gridRowStart),'auto');
        assert.ok((await card.boundingBox()).width > 500, 'Mobile test card must occupy the whole row');
        await fs.promises.mkdir('dev/output',{recursive:true});
        await card.screenshot({path:'dev/output/ls-futures-test-card.png'});
        assert.deepEqual(errors,[]);
        console.log('Test card: combined sessions, shared market/mode/drag, empty overnight axis interval, futures candles and mobile layout passed.');
    } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
